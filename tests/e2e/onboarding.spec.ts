import { localNow } from '../../apps/web/src/lib/format.js';
import { test, expect } from '@playwright/test';
test('registers, persists a private portfolio and signs out', async ({ page }, testInfo) => {
  test.setTimeout(60000);
  await page.goto('/');
  await page.getByLabel('Imię', { exact: true }).fill('Tester');
  await page.getByLabel('Adres email').fill(`e2e-${Date.now()}-${Math.random().toString(36).slice(2)}@example.com`);
  await page.getByLabel('Hasło', { exact: true }).fill('Test-only-passphrase-2026!');
  await page.getByRole('button', { name: 'Utwórz konto', exact: true }).click();
  await page.getByLabel('Nazwa portfela').fill('Portfel testowy');
  await page.getByRole('button', { name: 'Utwórz portfel', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Portfel testowy' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Portfel testowy' })).toBeVisible();
  const pln = page.getByRole('article').filter({ hasText: 'Gotówka PLN' });
  await page.getByLabel('Kwota', { exact: true }).fill('1000');
  await page.getByLabel('Notatka (opcjonalnie)').fill('Pierwsza wpłata');
  await page.getByRole('button', { name: 'Zapisz wpłatę', exact: true }).click();
  await expect(pln).toContainText('1 000,00');
  await page.getByLabel('Rodzaj operacji').selectOption('WITHDRAWAL');
  await page.getByLabel('Kwota', { exact: true }).fill('150');
  await page.getByRole('button', { name: 'Zapisz wypłatę', exact: true }).click();
  await expect(pln).toContainText('850,00');
  await page.getByLabel('Kwota', { exact: true }).fill('1000');
  await page.getByRole('button', { name: 'Zapisz wypłatę', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Brak wystarczających środków');
  await page.getByLabel('Rodzaj operacji').selectOption('DEPOSIT');
  await page.getByRole('combobox', { name: 'Waluta', exact: true }).selectOption('USD');
  await page.getByLabel('Kwota', { exact: true }).fill('10');
  await page.getByLabel('Kurs historyczny (PLN za 1 USD)', { exact: true }).fill('4,20');
  await page.getByRole('button', { name: 'Zapisz wpłatę', exact: true }).click();
  await expect(page.getByRole('article').filter({ hasText: 'Gotówka USD' })).toContainText('10,00');
  await expect(page.getByRole('article').filter({ hasText: 'Wpłaty netto' })).toContainText('892,00');
  await page.reload();
  await expect(pln).toContainText('850,00');
  await expect(page.getByText('Pierwsza wpłata', { exact: true })).toBeVisible();
  const editor = page.getByRole('group', { name: 'Wybierz formularz' });
  await editor.getByRole('button', { name: 'Instrument', exact: true }).click();
  await page.getByLabel('Nazwa instrumentu', { exact: true }).fill('Instrument testowy USD');
  await page.getByLabel('Symbol (ticker)', { exact: true }).fill('IKTEST');
  await page.getByLabel('Rynek (MIC)', { exact: true }).fill('XNAS');
  await page.getByRole('combobox', { name: 'Waluta instrumentu', exact: true }).selectOption('USD');
  await page.getByLabel('Precyzja ilości (0–10 miejsc)', { exact: true }).fill('3');
  await page.getByRole('button', { name: 'Dodaj instrument', exact: true }).click();
  await expect(page.getByText('Instrument dodany. Możesz zapisać zakup.', { exact: true })).toBeVisible();
  await editor.getByRole('button', { name: 'Kupno / sprzedaż', exact: true }).click();
  await page.getByLabel('Ilość (do 3 miejsc)', { exact: true }).fill('0,1');
  await page.getByLabel('Cena transakcji (USD)', { exact: true }).fill('80');
  await page.getByLabel('Prowizja (USD)', { exact: true }).fill('0,5');
  await page.getByLabel('Historyczny FX transakcji (PLN za 1 USD)', { exact: true }).fill('4,2');
  await page.getByLabel('Opis transakcji (opcjonalnie)', { exact: true }).fill('Pierwszy zakup');
  await page.getByRole('button', { name: 'Zapisz zakup', exact: true }).click();
  const usdCash = page.getByRole('article').filter({ hasText: 'Gotówka USD' });
  const portfolioValue = page.getByRole('article').filter({ hasText: 'Wartość portfela' });
  const pnl = page.getByRole('article').filter({ hasText: 'Wynik portfela' });
  await expect(usdCash).toContainText('1,50');
  await expect(page.getByText('Wycena niepełna', { exact: true })).toBeVisible();
  await expect(portfolioValue).toContainText('—');
  await editor.getByRole('button', { name: 'Cena ręczna', exact: true }).click();
  await page.getByLabel('Cena wyceny za sztukę (USD)', { exact: true }).fill('90');
  await page.getByLabel('Data i godzina ceny', { exact: true }).fill('2026-01-02T12:00');
  await page.getByRole('button', { name: 'Zapisz cenę', exact: true }).click();
  await expect(page.getByText('Cena starsza niż próg', { exact: true })).toBeVisible();
  await page.getByLabel('Cena wyceny za sztukę (USD)', { exact: true }).fill('90');
  await page.getByLabel('Data i godzina ceny', { exact: true }).fill(localNow());
  await page.getByRole('button', { name: 'Zapisz cenę', exact: true }).click();
  await expect(page.getByText('Cena zapisana. Wycena została przeliczona.', { exact: true })).toBeVisible();
  await editor.getByRole('button', { name: 'Kurs wyceny', exact: true }).click();
  await page.getByLabel('Kurs wyceny (PLN za 1 USD)', { exact: true }).fill('4,2');
  await page.getByRole('button', { name: 'Zapisz kurs wyceny', exact: true }).click();
  await expect(page.getByText('Wycena kompletna', { exact: true })).toBeVisible();
  await expect(portfolioValue).toContainText('894,10'); await expect(pnl).toContainText('2,10');
  await editor.getByRole('button', { name: 'Kupno / sprzedaż', exact: true }).click();
  await page.getByRole('combobox', { name: 'Rodzaj transakcji', exact: true }).selectOption('SELL');
  await page.getByLabel('Ilość (do 3 miejsc)', { exact: true }).fill('0,2');
  await page.getByLabel('Cena transakcji (USD)', { exact: true }).fill('100');
  await page.getByLabel('Prowizja (USD)', { exact: true }).fill('0,1');
  await page.getByLabel('Historyczny FX transakcji (PLN za 1 USD)', { exact: true }).fill('4,2');
  await page.getByRole('button', { name: 'Zapisz sprzedaż', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Nie możesz sprzedać większej ilości');
  await page.getByLabel('Ilość (do 3 miejsc)', { exact: true }).fill('0,05');
  await page.getByRole('button', { name: 'Zapisz sprzedaż', exact: true }).click();
  await expect(usdCash).toContainText('6,40'); await expect(portfolioValue).toContainText('895,78'); await expect(pnl).toContainText('3,78');
  await page.reload();
  await expect(portfolioValue).toContainText('895,78'); await expect(page.getByText('Pierwszy zakup', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('investments-desktop.png'), fullPage: true });

  const darkButton = page.getByRole('button', { name: 'Włącz ciemny motyw' });
  if (await darkButton.isVisible()) await darkButton.click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('article').filter({ hasText: 'Udział z gotówką' })).toContainText('18,90');
  await page.screenshot({ path: testInfo.outputPath('investments-mobile-dark.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Wyloguj' }).click();
  await expect(page.getByRole('heading', { name: 'Zacznij swój portfel' })).toBeVisible();
});
