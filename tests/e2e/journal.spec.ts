import { expect, test } from '@playwright/test';
import { instrumentsSchema, journalListSchema, journalInputSchema, portfoliosSchema, cashSummarySchema } from '@investorkit/shared';
test('persists private journal entries and protects edits across windows', async ({ page, browser, baseURL }, testInfo) => {
  test.setTimeout(60000);
  const setupHeaders = { origin: baseURL! };
  const signup = await page.request.post('/api/auth/sign-up/email', { headers: setupHeaders, data: { name: 'Journal tester', email: `journal-e2e-${Date.now()}-${Math.random().toString(36).slice(2)}@example.com`, password: 'Test-only-passphrase-2026!' } });
  expect(signup.status()).toBe(200);
  expect((await page.request.post('/api/v1/portfolios', { headers: setupHeaders, data: { name: 'Dziennik testowy' } })).status()).toBe(201);
  expect((await page.request.post('/api/v1/instruments', { headers: setupHeaders, data: { type: 'ETF', symbol: 'IKJ', mic: 'XWAR', name: 'Instrument do dziennika', currency: 'PLN', quantityScale: 0 } })).status()).toBe(201);
  const headers = { origin: baseURL! };
  const portfolios = await page.request.get('/api/v1/portfolios');
  const portfolio = portfoliosSchema.parse(await portfolios.json()).items[0]!;
  const instruments = await page.request.get('/api/v1/instruments');
  const instrument = instrumentsSchema.parse(await instruments.json()).items[0]!;
  const beforeCashResponse = await page.request.get(`/api/v1/portfolios/${portfolio.id}/cash`);
  const beforeCash = cashSummarySchema.parse(await beforeCashResponse.json());
  await page.goto('/#journal');
  const screen = page.getByRole('region', { name: 'Dziennik decyzji', exact: true });
  await expect(screen.getByText('Nie masz jeszcze wpisów.', { exact: false })).toBeVisible();
  await expect(page.getByRole('navigation', { name: 'Sekcje portfela' }).getByRole('link', { name: 'Dziennik', exact: true })).toHaveAttribute('aria-current', 'page');
  await page.getByRole('combobox', { name: 'Decyzja dotyczy' }).click();
  await page.getByRole('option', { name: `${instrument.symbol} · ${instrument.name}`, exact: true }).click();
  await page.getByLabel('Powód decyzji', { exact: true }).fill('Moja decyzja o ETF');
  await page.getByLabel('Teza inwestycyjna', { exact: true }).fill('Długoterminowa teza\nDruga linia');
  await page.getByLabel('Horyzont inwestycji (opcjonalnie)').fill('5 lat');
  await page.getByLabel('Ryzyka (opcjonalnie)').fill('Wahania wartości');
  await page.getByLabel('Warunki przeglądu decyzji (opcjonalnie)').fill('Zmiana moich założeń');
  await page.getByLabel('Notatki (opcjonalnie)').fill('<img src=x onerror=alert(1)>');
  await page.getByRole('button', { name: 'Zapisz wpis', exact: true }).click();
  const entry = page.getByRole('article', { name: 'Moja decyzja o ETF', exact: true });
  await expect(entry).toBeVisible(); await expect(entry).toContainText(instrument.symbol);
  await expect(screen).toContainText('Wpis zapisany.');
  await page.reload(); await expect(entry).toBeVisible();
  const details = entry.getByText('Pełny wpis', { exact: true });
  await details.focus(); await details.press('Enter');
  await expect(entry.getByText('<img src=x onerror=alert(1)>', { exact: true })).toBeVisible();
  await expect(entry.locator('img,script')).toHaveCount(0);
  await details.press('Space'); await expect(entry.getByText('5 lat', { exact: true })).toBeHidden();
  for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 844 });
    for (const theme of ['light', 'dark']) {
      const toggle = page.getByRole('button', { name: theme === 'dark' ? 'Włącz ciemny motyw' : 'Włącz jasny motyw' });
      if (await toggle.count()) await toggle.click();
      await screen.screenshot({ path: testInfo.outputPath(`journal-${width}-${theme}.png`), animations: 'disabled' });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    }
  }
  await entry.getByRole('button', { name: 'Edytuj wpis' }).click();
  await expect(page.getByRole('heading', { name: 'Edytuj wpis', exact: true })).toBeFocused();
  await expect(page.getByLabel('Teza inwestycyjna', { exact: true })).toHaveValue('Długoterminowa teza\nDruga linia');
  await page.getByLabel('Teza inwestycyjna', { exact: true }).fill('Mój niezapisany szkic');
  const entriesResponse = await page.request.get(`/api/v1/portfolios/${portfolio.id}/journal`);
  const list: unknown = await entriesResponse.json();
  const saved = journalListSchema.parse(list).items[0]!;
  const { id: _id, portfolioId: _portfolio, revision: _revision, createdAt: _created, updatedAt: _updated, ...savedInput } = saved;
  const updated = await page.request.patch(`/api/v1/journal/${saved.id}`, { headers: { ...headers, 'if-match': '"1"' }, data: journalInputSchema.parse({ ...savedInput, thesis: 'Teza z drugiego okna' }) });
  expect(updated.status()).toBe(200);
  await page.getByRole('button', { name: 'Zapisz zmiany', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Wpis zmienił się' })).toBeVisible();
  await expect(page.getByLabel('Teza inwestycyjna', { exact: true })).toHaveValue('Mój niezapisany szkic');
  await page.getByRole('button', { name: 'Odśwież wpisy', exact: true }).click();
  await expect(page.getByLabel('Teza inwestycyjna', { exact: true })).toHaveValue('Mój niezapisany szkic');
  await page.getByRole('button', { name: 'Wczytaj aktualną wersję (zastąpi formularz)', exact: true }).click();
  await expect(page.getByLabel('Teza inwestycyjna', { exact: true })).toHaveValue('Teza z drugiego okna');
  await page.getByLabel('Teza inwestycyjna', { exact: true }).fill('Teza po przeglądzie');
  await page.getByRole('button', { name: 'Zapisz zmiany', exact: true }).click();
  await expect(entry).toContainText('Teza po przeglądzie');
  await page.reload(); await expect(entry).toContainText('Teza po przeglądzie');
  const anonymous = await browser.newContext();
  try { expect((await anonymous.request.get(`${baseURL}/api/v1/portfolios/${portfolio.id}/journal`)).status()).toBe(401); } finally { await anonymous.close(); }
  await entry.getByRole('button', { name: 'Usuń wpis', exact: true }).click();
  await entry.getByRole('button', { name: 'Zachowaj wpis', exact: true }).click(); await expect(entry).toBeVisible();
  await entry.getByRole('button', { name: 'Usuń wpis', exact: true }).click();
  await entry.getByRole('button', { name: 'Tak, usuń wpis', exact: true }).click();
  await expect(entry).toHaveCount(0); await page.reload();
  await expect(screen.getByText('Nie masz jeszcze wpisów.', { exact: false })).toBeVisible();
  const cash = await page.request.get(`/api/v1/portfolios/${portfolio.id}/cash`);
  expect(cashSummarySchema.parse(await cash.json())).toEqual(beforeCash);
});
